def sc(
    scenario_id: str,
    profile: str,
    turns: str | tuple[str, ...],
    tags: dict[str, str],
    **expect: Any,
) -> Scenario:
    return Scenario(
        scenario_id,
        profile,
        (turns,) if isinstance(turns, str) else turns,
        Expectations(**expect),
        tags,
        representative=scenario_id in REPRESENTATIVE_IDS,
    )


